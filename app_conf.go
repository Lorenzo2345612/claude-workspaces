package main

import (
	"fmt"
	"strings"
)

// appTmuxConf is the tmux configuration of a workspace run by the app: no status bar, no prefix
// key and no menus — the window draws all of that — but mouse scrolling, selection and the
// clipboard keep working inside each terminal.
func appTmuxConf() string {
	var b strings.Builder
	w := func(format string, a ...any) { fmt.Fprintf(&b, format+"\n", a...) }
	w("# Generated by cw (app) — regenerated on every start; do not edit.")
	w(`set -g default-terminal "tmux-256color"`)
	w(`set -as terminal-features ",xterm*:RGB:clipboard:ccolour:cstyle:focus:title"`)
	w(`set -g escape-time 10`)
	w(`set -g history-limit 50000`)
	w(`set -g mouse on`)
	w(`set -g set-clipboard on`)
	w(`set -g allow-passthrough on`)
	w(`set -g focus-events on`)
	w(`set -g status off`)
	w(`set -g default-size 160x45`)
	w(`set -g window-size latest`)
	w(`set -g exit-empty on`)
	w(`set -g detach-on-destroy on`)
	w(`set -g base-index 1`)
	w(`setw -g pane-base-index 1`)
	w(`setw -g allow-rename off`)
	w(`setw -g automatic-rename off`)
	w(`setw -g aggressive-resize on`)
	w(`setw -g remain-on-exit failed`)
	w(`setw -g remain-on-exit-format ""`)
	w(`set -g mode-style "bg=colour61 fg=colour255"`)
	w(`set -g message-style "bg=colour236 fg=colour252"`)
	// Ctrl+B is Claude Code's "run in background" key: tmux gets no prefix at all.
	w(`set -g prefix None`)
	w(`set -g prefix2 None`)
	w(`unbind C-b`)
	// Wheel up enters scroll mode only when there is history to scroll; -e leaves it at the bottom.
	w(`bind -n WheelUpPane { if -F "#{||:#{pane_in_mode},#{mouse_any_flag}}" { send -M } { if -F "#{history_size}" { copy-mode -e } } }`)
	// Selecting with the mouse copies to the clipboard when the button comes up.
	w(`bind -n MouseDrag1Pane { if -F "#{||:#{pane_in_mode},#{mouse_any_flag}}" { send-keys -M } { copy-mode -M } }`)
	w(`bind -T copy-mode MouseDragEnd1Pane send -X copy-pipe-and-cancel`)
	w(`bind -T copy-mode-vi MouseDragEnd1Pane send -X copy-pipe-and-cancel`)
	// The window has its own right-click panel: tmux's pane menu stays out of the way.
	w(`unbind -n MouseDown3Pane`)
	w(`unbind -n M-MouseDown3Pane`)
	w(`unbind -n MouseDown3Status`)
	w(`unbind -n MouseDown3StatusLeft`)
	return b.String()
}
